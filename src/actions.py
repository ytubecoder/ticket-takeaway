def move_ticket(
    conn: sqlite3.Connection,
    project_id: str,
    ticket_id: str,
    target_section: str,
    project_path: str = "",
    actor: ActorContext = ActorContext.human(),
) -> str:
    """Move a ticket to *target_section*.

    Uses compute_status_on_move() to decide the new status (preserves the
    current status when it is valid in the target section).  Captures the
    HEAD commit hash when moving to Done. Emits M1a spine events
    `section_change` and (when status changes) `status_change`.

    Returns the canonical ticket ID.
    """
    ticket = _find_ticket(conn, project_id, ticket_id)
    tid = ticket["id"]
    old_section = ticket["section"]
    old_status = ticket["status"]

    new_status = compute_status_on_move(old_status, target_section)
    sort_order = _next_sort_order(conn, project_id, target_section)

    # Capture commit hash when moving to Done
    commit_hash_val = ""
    if target_section == "Done":
        commit_hash_val = capture_commit_hash(project_path)

    now = datetime.now().isoformat()

    if commit_hash_val:
        conn.execute(
            "UPDATE tickets SET section = ?, status = ?, sort_order = ?, "
            "updated_at = ?, commit_hash = ? "
            "WHERE id = ? AND project_id = ?",
            (
                target_section,
                new_status,
                sort_order,
                now,
                commit_hash_val,
                tid,
                project_id,
            ),
        )
    else:
        conn.execute(
            "UPDATE tickets SET section = ?, status = ?, sort_order = ?, "
            "updated_at = ? "
            "WHERE id = ? AND project_id = ?",
            (target_section, new_status, sort_order, now, tid, project_id),
        )

    # M1a spine events — emit BEFORE side-effect hooks so they appear first in history.
    if old_section != target_section:
        emit_event(
            conn,
            project_id,
            "ticket",
            tid,
            "section_change",
            {"before": old_section, "after": target_section},
            actor,
        )
    if old_status != new_status:
        emit_event(
            conn,
            project_id,
            "ticket",
            tid,
            "status_change",
            {"before": old_status, "after": new_status},
            actor,
        )

    # Post-change hooks. Phase A migration (tidy-newt) moved parent-promote
    # and auto-accept into system workflows; what remains here is the journey
    # cascade and commit-hash capture in _after_section_change.
    _after_section_change(conn, project_id, tid, old_section, target_section)
    _after_status_change(conn, project_id, tid, old_status, new_status)

    return tid


def accept_ticket(
    conn: sqlite3.Connection,
    project_id: str,
    ticket_id: str,
    project_path: str,
    project_name: str,
    actor: ActorContext = ActorContext.human(),
    force: str = "",
) -> str:
    """Accept a ticket: move to Done with status 'done' and append to PRODUCT_SPECIFICATION.md.

    This is the gate. Before anything is written it requires:

      * `verify_passed`   — a real verify run that exited 0 against current HEAD
      * `spec_validates`  — `openspec validate <change> --strict` exits 0, or an
                            explicit-and-justified lane-C claim of no delta

    A failing check raises ValueError; both callers turn that into a non-zero
    exit / an HTTP error. The checks run identically whether this is reached from
    `tickets-cli.py accept` or from a dashboard click, because there is exactly
    one implementation.

    On success the change is archived — merging its delta into
    `openspec/specs/` — *before* PRODUCT_SPECIFICATION.md is written, so the
    archive diff lands in the same commit as the accept rather than stranding a
    second diff that needs its own PR.

    *force* is the escape hatch: a non-empty string skips the gate but records
    the reason on the ticket and in the audit log. Silent bypass is not offered.

    Emits M1a spine events `section_change` and `status_change` as needed.
    Returns the canonical ticket ID.
    """
    ticket = _find_ticket(conn, project_id, ticket_id)
    tid = ticket["id"]
    old_section = ticket["section"]
    old_status = ticket["status"]

    gate = evaluate_accept_gate(conn, ticket)
    if not gate.passed and not force:
        raise ValueError(gate.refusal_message(project_id, tid))

    archive_note = ""
    if force:
        emit_event(
            conn,
            project_id,
            "ticket",
            tid,
            "gate_override",
            {"reason": force, "blocked_by": list(gate.failures)},
            actor,
        )
        write_readiness_flag(
            conn,
            project_id,
            tid,
            "spec",
            _forced_spec_flag_content(conn, project_id, tid, force),
            set_by="accept:--force",
        )
    else:
        archive_note = _archive_change_for(conn, project_id, tid, project_path)

    commit_hash_val = capture_commit_hash(project_path)
    sort_order = _next_sort_order(conn, project_id, "Done")
    now = datetime.now().isoformat()

    conn.execute(
        "UPDATE tickets SET section = 'Done', status = 'done', "
        "sort_order = ?, updated_at = ?, commit_hash = ? "
        "WHERE id = ? AND project_id = ?",
        (sort_order, now, commit_hash_val, tid, project_id),
    )

    if old_section != "Done":
        emit_event(
            conn,
            project_id,
            "ticket",
            tid,
            "section_change",
            {"before": old_section, "after": "Done"},
            actor,
        )
    if old_status != "done":
        emit_event(
            conn,
            project_id,
            "ticket",
            tid,
            "status_change",
            {"before": old_status, "after": "done"},
            actor,
        )

    # Append to PRODUCT_SPECIFICATION.md
    spec_path = Path(project_path) / "PRODUCT_SPECIFICATION.md"
    today = datetime.now().strftime("%Y-%m-%d")
    entry = f"\n### {tid}: {ticket['title']}\n"
    entry += f"Priority: {ticket['priority']} | Status: released\n"
    commit_info = f" | Commit: {commit_hash_val}" if commit_hash_val else ""
    entry += f"Released: {today}{commit_info}\n"
    # Record what the gate actually saw, so the spec says how this was proven
    # rather than merely that someone pressed accept.
    rec = verify_record(conn, project_id, tid)
    if rec.command:
        entry += f"Verified: `{rec.command}` exit {rec.exit_code}\n"
    if archive_note:
        entry += f"{archive_note}\n"
    if force:
        entry += f"Gate overridden: {force}\n"
    if ticket["description"]:
        entry += f"{ticket['description']}\n"

    if spec_path.exists():
        content = spec_path.read_text(encoding="utf-8")
        # Insert before ## Archive if it exists, otherwise append
        if "## Archive" in content:
            content = content.replace("## Archive", entry + "\n## Archive")
        else:
            content = content.rstrip() + "\n" + entry
        spec_path.write_text(content, encoding="utf-8")
    else:
        spec_path.write_text(
            f"# Product Specification \u2014 {project_name}\n{entry}\n",
            encoding="utf-8",
        )

    # Post-change hooks
    _after_section_change(conn, project_id, tid, old_section, "Done")
    _after_status_change(conn, project_id, tid, old_status, "done")

    return tid


def add_ticket(
    conn: sqlite3.Connection,
    project_id: str,
    title: str,
    section: str = "Backlog",
    priority: str = "medium",
    description: str = "",
    parent: str | None = None,
    draft: bool = False,
    source_attachment_id: int | None = None,
    tags: list[str] | None = None,
    is_container: int = 0,
    actor: ActorContext = ActorContext.human(),
    emit_created_event: bool = True,
) -> str:
    """Add a new ticket.  Auto-generates the ID from *section* prefix.

    Returns the new ticket ID.

    Callers that want to emit a richer ticket_created event themselves (e.g.
    seek attaches scan source-line metadata; seed_project tags origin=seed)
    should pass emit_created_event=False and call emit_event directly.
    """
    status = DEFAULT_STATUS_BY_SECTION[section]
    ticket_id = auto_generate_id(conn, project_id, section)
    sort_order = _next_sort_order(conn, project_id, section)

    conn.execute(
        "INSERT INTO tickets (id, project_id, title, priority, status, "
        "section, description, parent, sort_order, draft, source_attachment_id, is_container) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (
            ticket_id,
            project_id,
            title,
            priority,
            status,
            section,
            description,
            parent,
            sort_order,
            int(draft),
            source_attachment_id,
            1 if is_container else 0,
        ),
    )

    if tags:
        for tag in tags:
            tag = tag.strip().lower()
            if tag:
                conn.execute(
                    "INSERT OR IGNORE INTO ticket_tags (ticket_id, project_id, tag) "
                    "VALUES (?, ?, ?)",
                    (ticket_id, project_id, tag),
                )

    if emit_created_event:
        # Default origin: 'human' for direct UI/CLI creation, 'agent' when an
        # agent-actor calls in (e.g. workflow run that spawns a sub-ticket).
        origin = "agent" if actor.actor_type == "agent" else "human"
        emit_event(
            conn,
            project_id,
            "ticket",
            ticket_id,
            "ticket_created",
            {
                "id": ticket_id,
                "title": title,
                "section": section,
                "origin": origin,
                "draft": bool(draft),
            },
            actor,
        )

    return ticket_id


