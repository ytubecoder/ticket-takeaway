def capture_commit_hash(project_path: str) -> str:
    """Return the short commit hash of HEAD for *project_path*, or '' on failure."""
    if not project_path:
        return ""
    try:
        result = subprocess.run(
            ["git", "log", "-1", "--format=%h"],
            cwd=project_path,
            capture_output=True,
            text=True,
            timeout=5,
        )
        return result.stdout.strip() if result.returncode == 0 else ""
    except Exception:
        return ""


