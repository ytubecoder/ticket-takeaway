def _find_ticket(
    conn: sqlite3.Connection, project_id: str, ticket_id: str
) -> sqlite3.Row:
    """Locate a ticket by ID (case-insensitive). Raises TicketNotFoundError if not found."""
    ticket = conn.execute(
        "SELECT * FROM tickets WHERE UPPER(id) = UPPER(?) AND project_id = ?",
        (ticket_id, project_id),
    ).fetchone()
    if not ticket:
        raise TicketNotFoundError(
            f"Ticket '{ticket_id}' not found in project '{project_id}'."
        )
    return ticket


# --- Summary one-liner ----------------------------------------------------
#
# A short status sentence cached on the ticket. Regenerated by the
# "Refresh ticket summary" system workflow when the content hash changes.
# The hash inputs are intentionally narrow: only fields that meaningfully
# affect the *meaning* of "where is this ticket up to" — title, description,
# acceptance criteria (text + checked state), section, status, and the
# status of any direct child tickets (so a parent's summary reacts to a
# child being closed). Tags / priority / sort order are deliberately
# excluded so re-prioritising or tagging doesn't churn the summary.


def compute_summary_hash(
    conn: sqlite3.Connection, project_id: str, ticket_id: str
) -> str:
    """Return a stable short hex hash of the ticket fields that drive the summary.

    Returns '' if the ticket is not found.
    """
    row = conn.execute(
        "SELECT id, title, description, section, status FROM tickets "
        "WHERE UPPER(id) = UPPER(?) AND project_id = ?",
        (ticket_id, project_id),
    ).fetchone()
    if not row:
        return ""

    criteria_rows = conn.execute(
        "SELECT text, checked FROM acceptance_criteria "
        "WHERE ticket_id = ? AND project_id = ? "
        "ORDER BY sort_order ASC, id ASC",
        (row["id"], project_id),
    ).fetchall()
    children_rows = conn.execute(
        "SELECT id, status FROM tickets "
        "WHERE parent = ? AND project_id = ? ORDER BY id ASC",
        (row["id"], project_id),
    ).fetchall()

    parts = [
        row["title"] or "",
        row["description"] or "",
        row["section"] or "",
        row["status"] or "",
        "|".join(f"{int(bool(c['checked']))}:{c['text'] or ''}" for c in criteria_rows),
        "|".join(f"{c['id']}:{c['status'] or ''}" for c in children_rows),
    ]
    blob = "\x1f".join(parts).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()[:16]


def _next_sort_order(conn: sqlite3.Connection, project_id: str, section: str) -> int:
    """Return max(sort_order)+1 for *section*, or 0 if empty."""
    row = conn.execute(
        "SELECT COALESCE(MAX(sort_order), -1) + 1 AS next_order "
        "FROM tickets WHERE project_id = ? AND section = ?",
        (project_id, section),
    ).fetchone()
    return row["next_order"]


def auto_generate_id(conn: sqlite3.Connection, project_id: str, section: str) -> str:
    """Generate the next ticket ID for a section (e.g., B-14, BUG-10, I-03)."""
    prefix = SECTION_PREFIX.get(section, "B")
    sep = "-"
    pattern = f"{prefix}{sep}%"

    rows = conn.execute(
        "SELECT id FROM tickets WHERE project_id = ? AND id LIKE ?",
        (project_id, pattern),
    ).fetchall()

    max_num = 0
    for row in rows:
        tid = row["id"]
        suffix = tid[len(prefix) + len(sep) :]
        try:
            num = int(suffix)
            max_num = max(max_num, num)
        except ValueError:
            pass

    return f"{prefix}{sep}{max_num + 1:02d}"


