@dataclass(frozen=True)
class AcceptGate:
    """Result of evaluating the close conditions for one ticket."""

    passed: bool
    failures: tuple[str, ...] = ()
    evidence: tuple[str, ...] = ()

    def refusal_message(self, project_id: str, ticket_id: str) -> str:
        """A specific, actionable refusal — never a bare 'not allowed'."""
        lines = [f"Cannot accept {ticket_id}: the close gate refused.", ""]
        lines += [f"  - {f}" for f in self.failures]
        lines += [
            "",
            "Fix the above, or override deliberately and on the record:",
            f'  tickets-cli.py accept {project_id} {ticket_id} --force "<reason>"',
        ]
        return "\n".join(lines)


def evaluate_accept_gate(conn: sqlite3.Connection, ticket: sqlite3.Row) -> AcceptGate:
    """Evaluate the uniform close conditions. Same in every lane.

    Step 1 of the close (running verify) is a separate, explicit action — this
    reads the recorded result rather than running commands as a side effect of
    an accept.
    """
    failures: list[str] = []
    evidence: list[str] = []

    ok, reasons = _verify_passed(conn, ticket)
    (evidence if ok else failures).extend(reasons)

    # spec_validates can only restate spec_linked's complaint when no lane is
    # declared — and it would shell out to `openspec` to do it. Short-circuit so
    # the refusal reads as one problem rather than two.
    linked_ok, reasons = _spec_linked(conn, ticket)
    (evidence if linked_ok else failures).extend(reasons)
    if linked_ok:
        ok, reasons = _spec_validates(conn, ticket)
        (evidence if ok else failures).extend(reasons)

    return AcceptGate(
        passed=not failures,
        failures=tuple(dict.fromkeys(failures)),
        evidence=tuple(dict.fromkeys(evidence)),
    )


def _forced_spec_flag_content(
    conn: sqlite3.Connection, project_id: str, ticket_id: str, reason: str
) -> str:
    """Preserve any declared lane while stamping the override reason onto it."""
    link = spec_link(conn, project_id, ticket_id)
    lane = link.lane or "C"
    change = link.change or NO_CHANGE_SENTINEL
    return SpecLink(
        lane=lane, change=change, note=f"accepted with --force: {reason}"
    ).render()


def _archive_change_for(
    conn: sqlite3.Connection, project_id: str, ticket_id: str, project_path: str
) -> str:
    """Archive the ticket's OpenSpec change, merging its delta into canon.

    Returns a one-line note for PRODUCT_SPECIFICATION.md, or '' when there was
    nothing to archive. Raises ValueError if the archive is attempted and fails —
    a half-closed ticket whose spec never reached canon is worse than a refusal.
    """
    link = spec_link(conn, project_id, ticket_id)
    if not link.change or link.claims_no_change:
        return ""

    try:
        import openspec_adapter as osa
    except ImportError:
        return ""

    if not osa.change_exists(project_path, link.change):
        archived = osa.archived_change_dirs(project_path, link.change)
        if archived:
            return f"Spec: `{link.change}` (already archived)"
        return ""

    res = osa.archive(project_path, link.change)
    if not res.ok:
        raise ValueError(
            f"Cannot accept {ticket_id}: `openspec archive {link.change}` failed "
            f"({res.message}). The spec delta must reach openspec/specs/ before "
            f"the ticket closes."
        )
    summary = osa.archive_summary(res)
    totals = summary.get("totals") or {}
    counts = (
        ", ".join(f"{n} {k}" for k, n in totals.items() if isinstance(n, int) and n)
        or "no requirement changes"
    )
    return f"Spec: `{link.change}` archived to openspec/specs/ ({counts})"


def _tests_covered(
    conn: sqlite3.Connection, ticket: sqlite3.Row
) -> tuple[bool, list[str]]:
    """Return (covered, reasons). Opt-in predicate for stricter user gates.

    Migration 15 collapsed the tests/smoke readiness flags into acceptance
    criteria, so the legacy "tests readiness flag has content" path is gone.
    Paths:
      1. A passing `verified` flag — a real verify run against current HEAD.
      2. A linked journey that compiles + validates.
      3. Explicit ticket.no_test_required = 1 with a non-empty rationale note.

    Path 1 exists because this predicate was a live trap: six projects already
    carry `tests_covered` in their `Backlog → WIP` triggers, while
    `journey_tickets` is empty and nothing sets `no_test_required`. Every one of
    those tickets was unsatisfiable — if the engine were switched on they could
    never advance. Accepting verify evidence gives the predicate a route that
    projects actually use.
    """
    reasons: list[str] = []
    project_id = ticket["project_id"]
    ticket_id = ticket["id"]

    # Path 1: a recorded verify run that passed against the current commit.
    ok, why = _verify_passed(conn, ticket)
    if ok:
        return (True, why)

    # Path 2: any linked journey that compiles + validates.
    journey_rows = conn.execute(
        "SELECT journey_id FROM journey_tickets WHERE ticket_id = ? AND project_id = ?",
        (ticket_id, project_id),
    ).fetchall()
    for (journey_id,) in journey_rows:
        if _journey_compiles_and_validates(conn, project_id, journey_id):
            return (True, [f"linked journey {journey_id} compiles+validates"])

    # Path 3: explicit no_test_required with non-empty note.
    if (
        ticket["no_test_required"] == 1
        and (ticket["no_test_required_note"] or "").strip()
    ):
        return (True, ["no_test_required (explicit)"])

    # No path satisfied — explain. Verify comes first because it is the route
    # most tickets should take.
    reasons.extend(why)
    if journey_rows and not any(
        _journey_compiles_and_validates(conn, project_id, jid)
        for (jid,) in journey_rows
    ):
        reasons.append("linked journeys do not compile/validate")
    elif not journey_rows:
        reasons.append("no linked journey")
    if ticket["no_test_required"] != 1:
        reasons.append("no_test_required not set")
    elif not (ticket["no_test_required_note"] or "").strip():
        reasons.append("no_test_required has no rationale note")
    return (False, reasons)


def _ticket_eligibility(
    conn: sqlite3.Connection, ticket: sqlite3.Row
) -> EligibilityResult:
    """Eligibility for a ticket subject. See docs/KITCHEN.md §7."""
    reasons: list[str] = []
    project_id = ticket["project_id"]
    ticket_id = ticket["id"]

    mode = _automation_mode(conn, project_id, "ticket", ticket_id)
    if mode != "auto":
        reasons.append(f"automation_mode is {mode}, not auto")

    if ticket["section"] not in CANONICAL_SECTIONS_FOR_ELIGIBILITY:
        reasons.append(f"section {ticket['section']!r} is not Backlog/WIP/For Review")

    if ticket["draft"] == 1:
        reasons.append("ticket is draft")
    if ticket["archived"] == 1:
        reasons.append("ticket is archived")

    if not (ticket["description"] or "").strip():
        reasons.append("description is empty")

    crit_count = conn.execute(
        "SELECT COUNT(*) FROM acceptance_criteria WHERE ticket_id = ? AND project_id = ?",
        (ticket_id, project_id),
    ).fetchone()[0]
    if crit_count == 0:
        reasons.append("no acceptance criteria")

    deps_ok, dep_reasons = _deps_clear(conn, project_id, ticket_id)
    if not deps_ok:
        reasons.extend(dep_reasons)

    if _has_active_run(conn, project_id, "ticket", ticket_id):
        reasons.append("active run already exists")

    # Binding: no agent dispatch without a declared spec lane. This is the
    # entry gate into automation — the Kitchen must not hand a ticket to an
    # implementing agent on free text alone. Safe to enforce even with old
    # tickets around, because eligibility already requires automation_mode
    # 'auto' (per-ticket opt-in, default manual): a ticket only meets this
    # gate once someone deliberately switches it on, and declaring a lane is
    # part of switching it on. The exit gate (verify + validate + archive)
    # stays at accept.
    spec_ok, spec_reasons = _spec_linked(conn, ticket)
    if not spec_ok:
        reasons.append(spec_reasons[0])

    eligible = (
        mode == "auto"
        and spec_ok
        and ticket["section"] in CANONICAL_SECTIONS_FOR_ELIGIBILITY
        and ticket["draft"] != 1
        and ticket["archived"] != 1
        and (ticket["description"] or "").strip()
        and crit_count > 0
        and deps_ok
        and not _has_active_run(conn, project_id, "ticket", ticket_id)
    )
    return EligibilityResult(eligible=bool(eligible), reasons=tuple(reasons))


def _journey_eligibility(
    conn: sqlite3.Connection, project_id: str, journey_id: str
) -> EligibilityResult:
    """Eligibility for a journey subject. See docs/KITCHEN.md §7."""
    reasons: list[str] = []
    mode = _automation_mode(conn, project_id, "journey", journey_id)
    if mode != "auto":
        reasons.append(f"automation_mode is {mode}, not auto")
    if not _journey_compiles_and_validates(conn, project_id, journey_id):
        reasons.append("manifest does not compile/validate")
    if _has_active_run(conn, project_id, "journey", journey_id):
        reasons.append("active run already exists")
    eligible = (
        mode == "auto"
        and _journey_compiles_and_validates(conn, project_id, journey_id)
        and not _has_active_run(conn, project_id, "journey", journey_id)
    )
    return EligibilityResult(eligible=bool(eligible), reasons=tuple(reasons))


def eligibility(
    conn: sqlite3.Connection, project_id: str, subject_type: str, subject_id: str
) -> EligibilityResult:
    """Compute Kitchen eligibility for any subject. See docs/KITCHEN.md §7.

    Always returns reasons, even when eligible=True (for UI tooltips).
    """
    if subject_type == "ticket":
        try:
            ticket = _find_ticket(conn, project_id, subject_id)
        except ValueError:
            return EligibilityResult(False, (f"ticket {subject_id!r} not found",))
        return _ticket_eligibility(conn, ticket)
    if subject_type == "journey":
        return _journey_eligibility(conn, project_id, subject_id)
    if subject_type == "investigation":
        return EligibilityResult(False, ("investigations not implemented in M1a",))
    return EligibilityResult(False, (f"unknown subject_type {subject_type!r}",))


