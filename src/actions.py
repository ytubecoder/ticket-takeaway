def get_ticket_activity(
    conn: sqlite3.Connection,
    project_id: str,
    ticket_id: str,
    limit: int = 50,
    before: str | None = None,
) -> list[dict]:
    """Return activity_events for a ticket, newest-first, with optional cursor.

    Uses the (project_id, subject_type, subject_id, occurred_at DESC) index.
    Pagination cursor `before` is an ISO-8601 timestamp (exclusive upper bound).

    Returns a list of event dicts:
        {id, occurred_at, actor_type, actor_id, event_kind, payload, run_id}
    where run_id is extracted from payload['run_id'] when present.
    """
    limit = max(1, min(limit, 500))

    # Resolve canonical ID (subject_id stored case-sensitively by emit_event).
    row = conn.execute(
        "SELECT id FROM tickets WHERE UPPER(id) = UPPER(?) AND project_id = ?",
        (ticket_id, project_id),
    ).fetchone()
    tid = row["id"] if row else ticket_id

    if before:
        rows = conn.execute(
            "SELECT id, actor_type, actor_id, event_kind, payload_json, "
            "       occurred_at, discarded_run_id "
            "FROM activity_events "
            "WHERE project_id = ? AND subject_type = 'ticket' AND subject_id = ? "
            "  AND occurred_at < ? "
            "ORDER BY occurred_at DESC, id DESC LIMIT ?",
            (project_id, tid, before, limit),
        ).fetchall()
    else:
        rows = conn.execute(
            "SELECT id, actor_type, actor_id, event_kind, payload_json, "
            "       occurred_at, discarded_run_id "
            "FROM activity_events "
            "WHERE project_id = ? AND subject_type = 'ticket' AND subject_id = ? "
            "ORDER BY occurred_at DESC, id DESC LIMIT ?",
            (project_id, tid, limit),
        ).fetchall()

    # Resolve agent display names in one batch — for actor_type='agent', actor_id
    # is a run_id. Kitchen runs (integer ids) carry workflow_name in metadata_json;
    # workflow_bounce runs (uuid string ids) link to workflows.name.
    agent_run_ids: set[str] = {
        r["actor_id"] for r in rows if r["actor_type"] == "agent" and r["actor_id"]
    }
    actor_name_by_run: dict[str, str] = {}
    if agent_run_ids:
        # Try kitchen runs (numeric ids)
        numeric_ids = [rid for rid in agent_run_ids if rid.isdigit()]
        if numeric_ids:
            placeholders = ",".join("?" * len(numeric_ids))
            kitchen_rows = conn.execute(
                f"SELECT id, metadata_json FROM runs WHERE id IN ({placeholders})",
                numeric_ids,
            ).fetchall()
            for kr in kitchen_rows:
                try:
                    meta = json.loads(kr["metadata_json"] or "{}")
                except (json.JSONDecodeError, TypeError):
                    meta = {}
                name = meta.get("workflow_name") or meta.get("agent_name")
                if name:
                    actor_name_by_run[str(kr["id"])] = name
        # Try workflow_bounce runs (uuid ids)
        uuid_ids = [rid for rid in agent_run_ids if not rid.isdigit()]
        if uuid_ids:
            placeholders = ",".join("?" * len(uuid_ids))
            try:
                wf_rows = conn.execute(
                    f"SELECT wr.id AS id, w.name AS name "
                    f"FROM workflow_runs wr LEFT JOIN workflows w ON w.id = wr.workflow_id "
                    f"WHERE wr.id IN ({placeholders})",
                    uuid_ids,
                ).fetchall()
                for wr in wf_rows:
                    if wr["name"]:
                        actor_name_by_run[wr["id"]] = wr["name"]
            except sqlite3.OperationalError:
                # workflow_runs table may not exist on minimal schemas
                pass

    events = []
    for r in rows:
        try:
            payload = json.loads(r["payload_json"]) if r["payload_json"] else {}
        except (json.JSONDecodeError, TypeError):
            payload = {}
        actor_name = None
        if r["actor_type"] == "agent" and r["actor_id"]:
            actor_name = actor_name_by_run.get(r["actor_id"])
        events.append(
            {
                "id": r["id"],
                "occurred_at": r["occurred_at"],
                "actor_type": r["actor_type"],
                "actor_id": r["actor_id"],
                "actor_name": actor_name,
                "event_kind": r["event_kind"],
                "payload": payload,
                "run_id": payload.get("run_id"),
                "discarded_run_id": r["discarded_run_id"],
            }
        )
    return events


def get_children_summary(
    conn: sqlite3.Connection,
    project_id: str,
    parent_id: str,
) -> dict:
    """Return a rollup of children for a container ticket.

    Returns:
        {
            total: int,
            done: int,                       # section == 'Done'
            count_by_section: {section: n},
            count_by_status: {status: n},
        }
    """
    rows = conn.execute(
        "SELECT section, status FROM tickets "
        "WHERE parent = ? AND project_id = ? AND archived = 0",
        (parent_id, project_id),
    ).fetchall()

    count_by_section: dict[str, int] = {}
    count_by_status: dict[str, int] = {}
    done = 0
    for r in rows:
        count_by_section[r["section"]] = count_by_section.get(r["section"], 0) + 1
        count_by_status[r["status"]] = count_by_status.get(r["status"], 0) + 1
        if r["section"] == "Done":
            done += 1

    return {
        "total": len(rows),
        "done": done,
        "count_by_section": count_by_section,
        "count_by_status": count_by_status,
    }


# --- Bookmarks + Recents --------------------------------------------------
#
# Per-project, per-ticket UI state. Not event-emitting — these are personal
# navigation aids, not ticket state changes.

RECENTS_CAP = 20


def toggle_bookmark(conn: sqlite3.Connection, project_id: str, ticket_id: str) -> bool:
    """Toggle bookmark for a ticket. Returns the new bookmark state (True=bookmarked).

    Removing a bookmark also touches recents — unbookmarking counts as a
    'just viewed' signal so the ticket re-appears under Recents instead of
    vanishing entirely from the nav.
    """
    ticket = _find_ticket(conn, project_id, ticket_id)
    tid = ticket["id"]
    row = conn.execute(
        "SELECT 1 FROM ticket_bookmarks WHERE project_id = ? AND ticket_id = ?",
        (project_id, tid),
    ).fetchone()
    if row:
        conn.execute(
            "DELETE FROM ticket_bookmarks WHERE project_id = ? AND ticket_id = ?",
            (project_id, tid),
        )
        # Treat unbookmarking as a fresh view so the ticket lands in Recents.
        _touch_recent_row(conn, project_id, tid)
        conn.commit()
        return False
    conn.execute(
        "INSERT INTO ticket_bookmarks (project_id, ticket_id, created_at) VALUES (?, ?, ?)",
        (project_id, tid, utcnow_iso()),
    )
    conn.commit()
    return True


def _touch_recent_row(
    conn: sqlite3.Connection, project_id: str, ticket_id: str
) -> None:
    """Inner upsert + trim — no separate commit, callers commit as part of
    their own transaction."""
    conn.execute(
        """
        INSERT INTO ticket_recents (project_id, ticket_id, last_seen_at)
        VALUES (?, ?, ?)
        ON CONFLICT(project_id, ticket_id) DO UPDATE SET last_seen_at = excluded.last_seen_at
        """,
        (project_id, ticket_id, utcnow_iso()),
    )
    conn.execute(
        """
        DELETE FROM ticket_recents
        WHERE project_id = ?
          AND ticket_id NOT IN (
              SELECT ticket_id FROM ticket_recents
              WHERE project_id = ?
              ORDER BY last_seen_at DESC
              LIMIT ?
          )
        """,
        (project_id, project_id, RECENTS_CAP),
    )


def list_bookmarks(conn: sqlite3.Connection, project_id: str) -> list[dict]:
    """List bookmarked tickets for a project. Filters out tickets that no longer exist."""
    rows = conn.execute(
        """
        SELECT t.id AS id, t.title AS title, t.section AS section,
               t.status AS status, b.created_at AS created_at
        FROM ticket_bookmarks b
        INNER JOIN tickets t
          ON t.project_id = b.project_id AND t.id = b.ticket_id
        WHERE b.project_id = ?
        ORDER BY b.created_at DESC
        """,
        (project_id,),
    ).fetchall()
    return [dict(r) for r in rows]


def is_bookmarked(conn: sqlite3.Connection, project_id: str, ticket_id: str) -> bool:
    row = conn.execute(
        "SELECT 1 FROM ticket_bookmarks WHERE project_id = ? AND ticket_id = ?",
        (project_id, ticket_id),
    ).fetchone()
    return bool(row)


def touch_recent(conn: sqlite3.Connection, project_id: str, ticket_id: str) -> None:
    """Record that the user opened this ticket. Trims oldest beyond RECENTS_CAP."""
    ticket = _find_ticket(conn, project_id, ticket_id)
    _touch_recent_row(conn, project_id, ticket["id"])
    conn.commit()


def list_recents(
    conn: sqlite3.Connection, project_id: str, limit: int = RECENTS_CAP
) -> list[dict]:
    """List recently-opened tickets, newest first. Excludes tickets that
    are currently bookmarked — a ticket is in exactly one of Bookmarks or
    Recents at any time."""
    rows = conn.execute(
        """
        SELECT t.id AS id, t.title AS title, t.section AS section,
               t.status AS status, r.last_seen_at AS last_seen_at
        FROM ticket_recents r
        INNER JOIN tickets t
          ON t.project_id = r.project_id AND t.id = r.ticket_id
        LEFT JOIN ticket_bookmarks b
          ON b.project_id = r.project_id AND b.ticket_id = r.ticket_id
        WHERE r.project_id = ? AND b.ticket_id IS NULL
        ORDER BY r.last_seen_at DESC
        LIMIT ?
        """,
        (project_id, limit),
    ).fetchall()
    return [dict(r) for r in rows]
